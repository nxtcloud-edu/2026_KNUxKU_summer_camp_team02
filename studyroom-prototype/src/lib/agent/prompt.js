/** 상태 항목의 사람이 읽는 이름 */
const STATE_LABEL = {
  goalText: '오늘 목표',
  progressText: '마지막으로 확인한 진도',
  elapsedMin: '시작한 지',
  event: '방금 일어난 일',
  awayMin: '자리를 비운 시간',
  streakMin: '끊기지 않고 이어온 시간',
  recentTopics: '최근에 다룬 것',
  lastAnswer: '네가 방금 한 답',
}

const fmt = (key, v) => {
  if (key === 'elapsedMin' || key === 'awayMin' || key === 'streakMin') return `${Math.round(v)}분`
  if (key === 'goalText') return `"${v}"` // 원문 그대로 인용해야 해서 따옴표로 감싼다
  if (Array.isArray(v)) return v.join(', ')
  return String(v)
}

/**
 * 지금 상태 블록.
 *
 * spec.stateKeys 에 선언된 항목만 넣는다. 전부 넣으면 개념 질문에도 "자리를 3분 비웠다"가
 * 딸려 들어가서, 묻지도 않은 걸 캐릭터가 언급한다.
 * 값이 비면 그 줄을 아예 넣지 않는다 — "없음"이라고 적으면 모델이 그걸 말한다.
 */
export function buildState(state = {}, stateKeys = []) {
  const lines = []
  for (const k of stateKeys) {
    const v = state[k]
    if (v === undefined || v === null || v === '' || (Array.isArray(v) && !v.length)) continue
    lines.push(`- ${STATE_LABEL[k] || k}: ${fmt(k, v)}`)
  }
  if (!lines.length) return ''
  return `[지금 상태]\n${lines.join('\n')}`
}

/**
 * 최종 프롬프트를 만든다.
 *
 * @param {{seat:object, funcId:string, state?:object, settings?:object}} o
 * @returns {{system:string, spec:object, toneId:string, blocks:string[]}}
 */
export function buildPrompt({ seat, funcId = 'F1', state = {}, settings = {} }) {
  const spec = effectiveSpec(funcId, settings)
  const toneId = toneOf(seat)
  const fnBlock = FUNCTION_BLOCK[funcId] || FUNCTION_BLOCK.F1

  const blocks = [
    `너는 "${seat?.name || '메이트'}"이다.\n\n${COMMON_BLOCK}`,
    fnBlock,
    buildTone(toneId, spec.toneIntensity),
    buildConflict(toneId, funcId),
    buildState(state, spec.stateKeys),
  ].filter(Boolean)

  return { system: blocks.join('\n\n'), spec, toneId, blocks }
}
