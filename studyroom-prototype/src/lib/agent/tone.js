/** 예전 좌석의 성격 낱말 → 말투. 스키마 교체 전까지만 쓰는 다리 */
const FROM_TRAITS = { 차분함: 'T1', 장난스러움: 'T2', 친근함: 'T3', 다정함: 'T3', 활발함: 'T2', 끈질김: 'T4' }

/**
 * 좌석에서 말투를 꺼낸다.
 *
 * @deprecated traits 폴백은 좌석 스키마가 tone 으로 교체되면 지운다.
 * 지금 지우면 이미 저장된 브라우저에서 말투 레이어가 통째로 사라진다 —
 * 좌석은 개수만 확인하고 통과시키기 때문에 tone 이 undefined 인 채로 들어온다.
 */
export function toneOf(seat) {
  if (seat?.tone && TONE_BLOCK[seat.tone]) return seat.tone
  for (const t of seat?.traits || []) {
    if (FROM_TRAITS[t]) return FROM_TRAITS[t]
  }
  return 'T1'
}

/**
 * 말투 블록을 만든다.
 * @param {'full'|'low'|'none'} intensity
 */
export function buildTone(toneId, intensity = 'full') {
  if (intensity === 'none') return ''
  const id = TONE_BLOCK[toneId] ? toneId : 'T1'
  /**
   * 축약 강도에도 **공통 금지는 붙인다.**
   *
   * 예전에는 축약판만 돌려줘서, 짧은 발화(출제·목표 확인·페이스 케어)에는
   * "이모지 금지"·"사용자를 평가하지 않는다" 가 통째로 빠져 있었다.
   * 하필 평가가 제일 튀어나오기 쉬운 자리가 그 셋이다.
   */
  if (intensity === 'low') return `${TONE_BLOCK_LOW[id]}\n${TONE_COMMON}`
  return `${TONE_BLOCK[id]}\n\n공통:\n${TONE_COMMON}`
}

/** 충돌 보정 블록. 해당 조합이 아니면 빈 문자열 */
export function buildConflict(toneId, funcId) {
  const line = TONE_FUNC_CONFLICT[toneId]?.[funcId]
  if (!line) return ''
  return `[예외 규칙 — 지금 조합에만 적용. 위 말투 지시와 충돌하면 이쪽을 따른다]\n${line}`
}

